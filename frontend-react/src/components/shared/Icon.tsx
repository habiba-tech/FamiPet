interface IconProps {
  name: string
  className?: string
  style?: CSSProperties
  spin?: boolean
}

export function Icon({ name, className, style, spin }: IconProps) {
  const Glyph = ICONS[name] ?? Circle
  return (
    <i className={className} style={style}>
      <Glyph className={spin ? 'lucide-spin' : undefined} aria-hidden="true" />
    </i>
  )
}